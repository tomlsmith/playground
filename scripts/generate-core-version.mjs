import { execFileSync } from "node:child_process";
import { renameSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const [cargoCommand, manifestPath, outputPath] = process.argv.slice(2);

if (
  cargoCommand === undefined ||
  manifestPath === undefined ||
  outputPath === undefined
) {
  throw new Error(
    "usage: generate-core-version.mjs <cargo> <Cargo.toml> <output.ts>",
  );
}

const metadata = JSON.parse(
  execFileSync(
    cargoCommand,
    [
      "metadata",
      "--locked",
      "--format-version",
      "1",
      "--manifest-path",
      resolve(manifestPath),
    ],
    { encoding: "utf8" },
  ),
);
const rootId = metadata.resolve?.root;
const rootNode = metadata.resolve?.nodes.find(({ id }) => id === rootId);
const coreId = rootNode?.deps.find(({ name }) => name === "tomlsmith")?.pkg;
const corePackage = metadata.packages.find(({ id }) => id === coreId);

if (corePackage?.version === undefined) {
  throw new Error(
    "cargo metadata did not resolve the direct tomlsmith dependency",
  );
}

const destination = resolve(outputPath);
const temporary = `${destination}.${process.pid}.tmp`;
const source = [
  "// Generated by scripts/build-wasm.sh; do not edit or commit.",
  `export const TOMLSMITH_CORE_VERSION = ${JSON.stringify(corePackage.version)};`,
  "",
].join("\n");

writeFileSync(temporary, source);
renameSync(temporary, destination);
process.stdout.write(`TomlSmith core ${corePackage.version}\n`);
